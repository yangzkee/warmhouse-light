# Generate 5x7 column LSB=top, 5+0 pad, matches Core/Src/oled.c digit '0' pattern


def row_to_cols(c, rows):
    r = [x.center(5) for x in rows]
    cols = []
    for col in range(5):
        b = 0
        for row in range(7):
            if r[row][col] == "#":
                b |= 1 << row
        cols.append(f"0x{b:02X}u")
    return "{" + ",".join(cols) + ",0x00u}, /* " + c + " */"


